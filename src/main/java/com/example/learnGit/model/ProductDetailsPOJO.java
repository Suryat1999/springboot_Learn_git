package com.example.learnGit.model;


public class ProductDetailsPOJO {

	private String prodId;
	private String prodName;
	private String prodDescription;
	private int orderbyNo;
	private String prodCatagery;
	public String getProdId() {
		return prodId;
	}
	public void setProdId(String prodId) {
		this.prodId = prodId;
	}
	public String getProdName() {
		return prodName;
	}
	public void setProdName(String prodName) {
		this.prodName = prodName;
	}
	public String getProdDescription() {
		return prodDescription;
	}
	public void setProdDescription(String prodDescription) {
		this.prodDescription = prodDescription;
	}
	public int getOrderbyNo() {
		return orderbyNo;
	}
	public void setOrderbyNo(int orderbyNo) {
		this.orderbyNo = orderbyNo;
	}
	public String getProdCatagery() {
		return prodCatagery;
	}
	public void setProdCatagery(String prodCatagery) {
		this.prodCatagery = prodCatagery;
	}
	
	
	
}
